CREATE TABLE IF NOT EXISTS `elys_store_bindings` (
  `id` BIGINT UNSIGNED NOT NULL,
  `created_at` DATETIME(3) DEFAULT NULL,
  `updated_at` DATETIME(3) DEFAULT NULL,
  `deleted_at` DATETIME(3) DEFAULT NULL,
  `store_id` BIGINT UNSIGNED NOT NULL,
  `elys_shop_id` BIGINT UNSIGNED NOT NULL,
  `elys_master_shop_id` BIGINT UNSIGNED NOT NULL DEFAULT 0,
  `meituan_authorized` TINYINT(1) NOT NULL DEFAULT 0,
  `douyin_authorized` TINYINT(1) NOT NULL DEFAULT 0,
  `last_auth_at` DATETIME(3) DEFAULT NULL,
  `status` TINYINT NOT NULL DEFAULT 1,
  `last_error` VARCHAR(255) NOT NULL DEFAULT '',
  PRIMARY KEY (`id`),
  UNIQUE KEY `uk_elys_binding_store` (`store_id`),
  UNIQUE KEY `uk_elys_binding_shop` (`elys_shop_id`),
  KEY `idx_elys_binding_deleted_at` (`deleted_at`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS `elys_voucher_verifications` (
  `id` BIGINT UNSIGNED NOT NULL,
  `created_at` DATETIME(3) DEFAULT NULL,
  `updated_at` DATETIME(3) DEFAULT NULL,
  `deleted_at` DATETIME(3) DEFAULT NULL,
  `store_id` BIGINT UNSIGNED NOT NULL,
  `elys_shop_id` BIGINT UNSIGNED NOT NULL,
  `platform` VARCHAR(16) NOT NULL,
  `voucher_code` VARCHAR(512) NOT NULL,
  `ticket_name` VARCHAR(255) NOT NULL DEFAULT '',
  `deal_id` VARCHAR(128) NOT NULL DEFAULT '',
  `pay_amount` BIGINT NOT NULL DEFAULT 0,
  `actual_pay_amount` BIGINT NOT NULL DEFAULT 0,
  `wxdg_order_no` VARCHAR(128) DEFAULT NULL,
  `platform_order_id` VARCHAR(128) NOT NULL DEFAULT '',
  `receipt_code` VARCHAR(128) NOT NULL DEFAULT '',
  `consume_credential_enc` TEXT,
  `ticket_info_enc` TEXT,
  `user_id` BIGINT UNSIGNED NOT NULL,
  `status` TINYINT NOT NULL DEFAULT 10,
  `error_code` VARCHAR(64) NOT NULL DEFAULT '',
  `error_message` VARCHAR(512) NOT NULL DEFAULT '',
  `prepare_token` VARCHAR(64) NOT NULL,
  `trace_id` VARCHAR(128) NOT NULL DEFAULT '',
  `consumed_at` DATETIME(3) DEFAULT NULL,
  `credited_at` DATETIME(3) DEFAULT NULL,
  PRIMARY KEY (`id`),
  UNIQUE KEY `uk_elys_prepare_token` (`prepare_token`),
  UNIQUE KEY `uk_elys_wxdg_order` (`wxdg_order_no`),
  KEY `idx_elys_verification_store` (`store_id`, `created_at`),
  KEY `idx_elys_verification_user` (`user_id`),
  KEY `idx_elys_verification_code` (`platform`, `voucher_code`),
  KEY `idx_elys_verification_status` (`status`),
  KEY `idx_elys_verification_deleted_at` (`deleted_at`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

